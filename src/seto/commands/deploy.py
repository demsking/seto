logger = logging.getLogger(__name__)


def parse_service_vars(entries: dict[str, Any], hostname: str) -> None:
  for key, value in entries.items():
    if isinstance(value, str):
      entries[key] = re.sub(NODE_HOSTNAME_RE, hostname, value)


def get_label_value(labels: dict[str, Any], name: str) -> Any | str:
  for label, value in labels.items():
    if label.endswith(name):
      return value
  return ''


def pick_label_value(labels: dict[str, Any], name: str) -> Any | str:
  for label, value in labels.items():
    if label.endswith(name):
      del labels[label]
      return value
  return ''


def parse_compose_config(
  args,
  driver: Driver,
  client: DockerClient,
  networks_list: list[str],
  swarm_config: dict,
  *,
  compose_config: dict,
  placement: str | list[str],
  composes: list[DockerCompose],
) -> None:
  if compose_config['services']:
    compose = DockerCompose(
      client=client,
      driver=driver,
      config=compose_config,
    )

    composes.append(compose)


def pull_and_push_images(config: dict, image_prefix: str) -> None:
  """Pull each service's original (un-prefixed) image and re-tag/push it under image_prefix.

  For services that have a ``build`` key generated by seto's volumes-image logic the
  ``image`` field already carries the prefixed name (e.g. ``registry/stack-svc:tag``).
  We derive the *original* image by stripping the prefix from the image name and use
  that as the pull source, then tag and push under the prefixed name.

  For services without a ``build`` key (plain ``image`` references) we pull, re-tag
  under ``image_prefix``, and push only when ``image_prefix`` is non-empty.
  """
  services = config.get('services', {})

  for service_name, service in services.items():
    prefixed_image = service.get('image', '')

    if not prefixed_image:
      continue

    if 'build' in service:
      # The prefixed image name was generated by seto (volumes-image path).
      # Derive the original image: strip the image_prefix to get the base name,
      # then reconstruct the upstream reference from the Dockerfile's FROM line.
      build_ctx = service['build']
      dockerfile_path = build_ctx.get('dockerfile', '') if isinstance(build_ctx, dict) else ''

      original_image = None

      if dockerfile_path:
        try:
          with open(dockerfile_path, encoding='utf-8') as fh:
            for line in fh:
              line = line.strip()
              if line.upper().startswith('FROM '):
                original_image = line.split(None, 1)[1].strip()
                break
        except OSError as exc:
          logger.warning("Could not read Dockerfile '%s': %s", dockerfile_path, exc)

      if not original_image:
        logger.warning(
          "Service '%s': cannot determine original image for pull — skipping.", service_name
        )
        continue
    else:
      # Plain image reference: pull as-is and re-tag under image_prefix (if set).
      if not image_prefix:
        continue

      original_image = prefixed_image
      service_image_name = prefixed_image.split('/')[-1]  # basename
      prefixed_image = f'{image_prefix}{service_image_name}'

    logger.info("Pulling '%s'...", original_image)
    subprocess.run(['docker', 'pull', original_image], check=True)

    if original_image != prefixed_image:
      logger.info("Tagging '%s' → '%s'...", original_image, prefixed_image)
      subprocess.run(['docker', 'tag', original_image, prefixed_image], check=True)

    logger.info("Pushing '%s'...", prefixed_image)
    subprocess.run(['docker', 'push', prefixed_image], check=True)


def deploy_seto_stack(args, driver: Driver) -> None:
  # Temporary rewrite driver config
  driver.namespace = f'seto-{args.namespace}'
  driver.stack = None

  # Building seto config
  client = DockerClient.from_env()
  namespace_networks = resolve_networks(args.namespace)

  logger.info('Configuring seto namespace agent...')
  internal_stack = {
    'networks': namespace_networks,
    'services': {
      'agent': {
        'image': 'busybox',
        'command': ['sleep', 'infinity'],
        'networks': list(namespace_networks.keys()),
        'deploy': {
          'mode': 'global',
        },
      },
    },
  }

  # Resolving compose local volumes
  resolved_compose_data, volumes = resolve_compose_file(
    driver=driver,
    image_prefix=args.image_prefix,
    compose_data=internal_stack,
    default_volume_mount_mode=args.default_volume_mount_mode,
    default_nfs_options=args.default_nfs_options,
    inject=True,
  )

  logger.info('Creating seto namespace volumes...')
  driver.create_volumes(
    volumes=volumes,
    sync=getattr(args, 'sync', True),
    force=getattr(args, 'force', False),
  )

  logger.info('Deploying seto namespace services...')
  swarm = DockerSwarm(
    client=client,
    driver=driver,
    config=resolved_compose_data,
  )

  swarm.info()
  swarm.deploy()
  swarm.ps()
  swarm.logs()

  # Restore initial driver config
  driver.namespace = args.namespace
  driver.stack = args.stack


def execute_deploy_command(args, driver: Driver) -> None:
  client = DockerClient.from_env()
  all_volumes = parse_volumes_args(args, driver)

  if all_volumes:
    logger.info('Automatically creating shared volumes...')

    driver.connect()
    driver.create_volumes(
      volumes=all_volumes,
      sync=getattr(args, 'sync', True),
      force=getattr(args, 'force', False),
    )
    driver.apply_storage_node_changes()
    driver.terminate()

  logger.info('Resolving %s services...', driver.stack_id)
  setattr(args, 'compose', False)
  swarm_config = resolve(args, driver)

  swarm = DockerSwarm(
    client=client,
    driver=driver,
    config=swarm_config,
  )

  setattr(args, 'compose', True)
  networks_list = list(swarm_config['networks'].keys())
  composes_items: list[DockerCompose] = []

  resolve(
    args,
    driver,
    inject=True,
    execute=lambda config, placement: parse_compose_config(
      args,
      driver,
      client,
      networks_list,
      swarm_config,
      compose_config=config,
      placement=placement,
      composes=composes_items,
    ),
  )

  use_pull = getattr(args, 'pull', False)

  if swarm_config['services']:
    if use_pull:
      logger.info('Pulling and pushing %s swarm images...', driver.stack_id)
      pull_and_push_images(swarm_config, args.image_prefix)
    else:
      logger.info('Building %s swarm images...', driver.stack_id)
      swarm.build()

      logger.info('Pushing %s images...', driver.stack_id)
      swarm.push()

    logger.info('Deploying %s swarm environment...', driver.stack_id)

    if logger.level == logging.DEBUG:
      swarm.info()

    swarm.deploy()

    if logger.level == logging.DEBUG:
      swarm.ps()
      swarm.logs()

  if composes_items:
    if use_pull:
      logger.info('Pulling and pushing %s compose images...', driver.stack_id)
      for compose in composes_items:
        pull_and_push_images(compose.config, args.image_prefix)
    else:
      logger.info('Building %s compose images...', driver.stack_id)
      for compose in composes_items:
        compose.build()
        compose.push()

    logger.info('Pulling %s compose images...', driver.stack_id)

    for compose in composes_items:
      if logger.level == logging.DEBUG:
        compose.info()

      compose.pull()

    logger.info('Deploying %s compose environment...', driver.stack_id)

    for compose in composes_items:
      compose.deploy()

      if logger.level == logging.DEBUG:
        compose.ps()
        compose.logs()
